// Generates supabase/seed.sql from data/demo-menu.json  →  npm run seed:sql
import { readFileSync, writeFileSync } from 'node:fs';

const menu = JSON.parse(readFileSync(new URL('../data/demo-menu.json', import.meta.url), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `ARRAY[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`);

const rows = menu
  .map(
    (m, i) =>
      `  ('H101', ${q(m.name)}, ${q(m.description)}, ${q(m.category)}, ${m.price * 100}, ${m.is_veg}, ${m.spice_level}, ${m.is_kitchen_item}, ${arr(m.allergens)}, ${i})`,
  )
  .join(',\n');

const sql = `-- Demo seed (generated by scripts/gen-seed.mjs)
insert into hotels (id, name, address, phone, gstin, gst_rate, footer_message)
values ('H101', 'Hotel Vigna Residency', '12, Anna Salai, Chennai 600002', '+91 44 4000 0101',
        '33ABCDE1234F1Z5', 5, 'Thank you for dining with us. Visit again!')
on conflict (id) do nothing;

insert into room_stays (hotel_id, room_no, guest_name, check_in, check_out, status)
values ('H101', '305', 'Arjun Mehta', now() - interval '1 day', now() + interval '3 days', 'active');

insert into menu_items (hotel_id, name, description, category, price_paise, is_veg, spice_level, is_kitchen_item, allergens, sort)
values
${rows};
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log('Wrote supabase/seed.sql');
